-- 001_initial_schema.sql
-- Core schema for the Expense Voucher Management System.
-- Business rules from the requirements are enforced here as well as in the API,
-- so the data stays consistent even if a bug slips into application code.

-- ---------------------------------------------------------------------------
-- Enumerations
-- ---------------------------------------------------------------------------

CREATE TYPE user_role AS ENUM ('EMPLOYEE', 'DIRECTOR', 'ACCOUNTS');

-- "Submitted" is recorded as an event (submitted_at + a SUBMITTED history row);
-- a submitted voucher sits in PENDING_APPROVAL until the Director decides.
CREATE TYPE voucher_status AS ENUM ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED');

CREATE TYPE voucher_event_type AS ENUM ('CREATED', 'UPDATED', 'SUBMITTED', 'APPROVED', 'REJECTED');

-- ---------------------------------------------------------------------------
-- Shared trigger: keep updated_at current
-- ---------------------------------------------------------------------------

CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Lookup tables
-- ---------------------------------------------------------------------------

CREATE TABLE departments (
  id         INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name       VARCHAR(80) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE expense_categories (
  id         INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name       VARCHAR(80) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------------

CREATE TABLE users (
  id             INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  full_name      VARCHAR(120) NOT NULL CHECK (length(btrim(full_name)) > 0),
  email          VARCHAR(254) NOT NULL,
  password_hash  TEXT NOT NULL,
  role           user_role NOT NULL,
  employee_code  VARCHAR(30) UNIQUE,              -- optional, per requirements
  department_id  INTEGER REFERENCES departments (id),
  signature_path TEXT,                            -- saved signature, reusable on vouchers
  is_active      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email));

CREATE TRIGGER users_set_updated_at
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- Vouchers
-- ---------------------------------------------------------------------------

-- Voucher numbers are generated by the database: EV-<year>-<5-digit sequence>.
-- A single sequence keeps them unique across years; gaps can appear when a
-- draft is deleted, which is normal for sequence-backed numbering.
CREATE SEQUENCE voucher_number_seq START WITH 1;

CREATE TABLE vouchers (
  id                      INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  voucher_number          VARCHAR(20) NOT NULL UNIQUE
                            DEFAULT ('EV-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('voucher_number_seq')::text, 5, '0')),
  voucher_date            DATE NOT NULL DEFAULT CURRENT_DATE,
  expense_date            DATE NOT NULL,
  department_id           INTEGER NOT NULL REFERENCES departments (id),
  category_id             INTEGER NOT NULL REFERENCES expense_categories (id),
  title                   VARCHAR(150) NOT NULL CHECK (length(btrim(title)) > 0),
  description             TEXT,
  amount                  NUMERIC(12, 2) NOT NULL CHECK (amount > 0),

  -- Employee information
  employee_id             INTEGER NOT NULL REFERENCES users (id),
  employee_signature_path TEXT,

  -- Approval information
  status                  voucher_status NOT NULL DEFAULT 'DRAFT',
  submitted_at            TIMESTAMPTZ,
  decided_by              INTEGER REFERENCES users (id),
  decided_at              TIMESTAMPTZ,          -- approval (or rejection) date
  director_signature_path TEXT,
  rejection_reason        TEXT,

  -- Audit information
  created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT vouchers_expense_not_after_voucher
    CHECK (expense_date <= voucher_date),
  -- Business rule 12: every submitted voucher carries the employee's signature.
  CONSTRAINT vouchers_submitted_has_signature
    CHECK (status = 'DRAFT' OR (employee_signature_path IS NOT NULL AND submitted_at IS NOT NULL)),
  -- Decision fields are filled exactly when a decision has been made.
  CONSTRAINT vouchers_decision_fields
    CHECK ((status IN ('APPROVED', 'REJECTED')) = (decided_by IS NOT NULL AND decided_at IS NOT NULL)),
  -- Business rule 13: every approved voucher carries the Director's signature.
  CONSTRAINT vouchers_approved_has_director_signature
    CHECK (status <> 'APPROVED' OR director_signature_path IS NOT NULL),
  -- Business rule 8: rejected vouchers must include a reason.
  CONSTRAINT vouchers_rejected_has_reason
    CHECK (status <> 'REJECTED' OR length(btrim(coalesce(rejection_reason, ''))) > 0)
);

ALTER SEQUENCE voucher_number_seq OWNED BY vouchers.voucher_number;

CREATE INDEX vouchers_employee_created_idx ON vouchers (employee_id, created_at DESC);
CREATE INDEX vouchers_status_idx           ON vouchers (status);
CREATE INDEX vouchers_voucher_date_idx     ON vouchers (voucher_date);
CREATE INDEX vouchers_department_idx       ON vouchers (department_id);
CREATE INDEX vouchers_category_idx         ON vouchers (category_id);
CREATE INDEX vouchers_decided_at_idx       ON vouchers (decided_at DESC) WHERE decided_at IS NOT NULL;

CREATE TRIGGER vouchers_set_updated_at
  BEFORE UPDATE ON vouchers
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Workflow guard. Allowed transitions:
--   DRAFT            -> DRAFT (edit) | PENDING_APPROVAL (submit)
--   PENDING_APPROVAL -> APPROVED | REJECTED   (employee-entered details frozen)
-- APPROVED and REJECTED are terminal, and only drafts can be deleted.
CREATE FUNCTION enforce_voucher_workflow() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status <> 'DRAFT' THEN
      RAISE EXCEPTION 'Only draft vouchers can be deleted (voucher % is %)', OLD.voucher_number, OLD.status
        USING ERRCODE = 'check_violation';
    END IF;
    RETURN OLD;
  END IF;

  IF OLD.status = 'DRAFT' AND NEW.status IN ('DRAFT', 'PENDING_APPROVAL') THEN
    RETURN NEW;
  END IF;

  IF OLD.status = 'PENDING_APPROVAL' AND NEW.status IN ('APPROVED', 'REJECTED') THEN
    IF (NEW.voucher_number, NEW.voucher_date, NEW.expense_date, NEW.department_id, NEW.category_id,
        NEW.title, NEW.description, NEW.amount, NEW.employee_id, NEW.employee_signature_path, NEW.submitted_at)
       IS DISTINCT FROM
       (OLD.voucher_number, OLD.voucher_date, OLD.expense_date, OLD.department_id, OLD.category_id,
        OLD.title, OLD.description, OLD.amount, OLD.employee_id, OLD.employee_signature_path, OLD.submitted_at)
    THEN
      RAISE EXCEPTION 'Voucher details cannot change once submitted (voucher %)', OLD.voucher_number
        USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;

  RAISE EXCEPTION 'Invalid voucher status change % -> % (voucher %)', OLD.status, NEW.status, OLD.voucher_number
    USING ERRCODE = 'check_violation';
END;
$$;

CREATE TRIGGER vouchers_enforce_workflow
  BEFORE UPDATE OR DELETE ON vouchers
  FOR EACH ROW EXECUTE FUNCTION enforce_voucher_workflow();

-- ---------------------------------------------------------------------------
-- Voucher history (audit trail and "recent activity")
-- ---------------------------------------------------------------------------

CREATE TABLE voucher_events (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  voucher_id  INTEGER NOT NULL REFERENCES vouchers (id) ON DELETE CASCADE,
  actor_id    INTEGER NOT NULL REFERENCES users (id),
  event_type  voucher_event_type NOT NULL,
  from_status voucher_status,
  to_status   voucher_status NOT NULL,
  note        TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX voucher_events_voucher_idx ON voucher_events (voucher_id, created_at);
CREATE INDEX voucher_events_recent_idx  ON voucher_events (created_at DESC);
